package com.geo.analytics.domain.enums;

/**
 * 解析ごとの4人のAIの議論の状態（#197）。{@code jobs.debate_status} に持つ。
 *
 * <p>Why: 結果画面は、議論が終わるまで問い合わせを続け、終わり方に応じて表示を変える（#198 / #200）。
 * 列が NULL のジョブは、この状態を持つ前の解析で、発言が保存されていない。
 */
public enum DebateStatus {
    /** 議論（または総合診断の作成）が終わっていない。発言がまだ0件なら準備中。 */
    RUNNING,
    /** 議論が終わり、総合診断が議論をもとに作られた。 */
    COMPLETED,
    /** 議論をせずに総合診断を作った（質問が2本未満・課金の識別子が揃わない など）。 */
    SKIPPED,
    /** 議論が失敗し、チケットを返して議論なしで総合診断を作った。途中までの発言は消してある。 */
    FAILED
}
